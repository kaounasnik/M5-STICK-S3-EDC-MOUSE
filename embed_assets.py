import os

Import("env")

project_dir = env["PROJECT_DIR"]
src_dir = os.path.join(project_dir, "src")
h_path = os.path.join(src_dir, "embedded_assets.h")
c_path = os.path.join(src_dir, "embedded_assets.c")

assets = [
    ("PNG", "screen_png", os.path.join(src_dir, "screen.png"), False),
    ("GIF", "screen_gif", os.path.join(src_dir, "screen.gif"), False),
    ("SVG", "screen_svg", os.path.join(src_dir, "screen.svg"), True),
]

sig_parts = []
present = []

for macro, sym, path, add_null in assets:
    if os.path.isfile(path) and os.path.getsize(path) > 0:
        st = os.stat(path)
        sig_parts.append(f"{macro}={st.st_size}:{int(st.st_mtime)}")
        present.append((macro, sym, path, add_null, st.st_size))
    else:
        sig_parts.append(f"{macro}=0:0")
        present.append((macro, sym, path, add_null, 0))

sig_line = "// SIG: " + "|".join(sig_parts)

# Skip regeneration if assets haven't changed (keeps rebuilds instant)
needs_regen = True
if os.path.isfile(h_path) and os.path.isfile(c_path):
    with open(h_path, "r", encoding="utf-8") as f:
        if f.readline().strip() == sig_line:
            needs_regen = False

if needs_regen:
    h_lines = [
        sig_line,
        "// Auto-generated by embed_assets.py - do not edit manually",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
    ]

    c_lines = [
        sig_line,
        "// Auto-generated by embed_assets.py - do not edit manually",
        '#include "embedded_assets.h"',
        "",
    ]

    any_embedded = False

    for macro, sym, path, add_null, size in present:
        if size > 0:
            any_embedded = True
            with open(path, "rb") as f:
                data = f.read()

            h_lines.append(f"#define HAS_SCREEN_{macro} 1")
            h_lines.append(f"extern const uint8_t {sym}_data[];")
            h_lines.append(f"extern const size_t {sym}_size;")
            h_lines.append("")

            c_lines.append(f"const size_t {sym}_size = {len(data)};")
            c_lines.append(f"const uint8_t {sym}_data[] = {{")
            for i in range(0, len(data), 16):
                chunk = data[i : i + 16]
                hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
                c_lines.append(f"    {hex_str},")
            if add_null:
                c_lines.append("    0x00")
            c_lines.append("};")
            c_lines.append("")
        else:
            h_lines.append(f"#define HAS_SCREEN_{macro} 0")
            h_lines.append("")

    h_lines.extend([
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ])

    if not any_embedded:
        c_lines.append("const int embedded_assets_placeholder = 0;")
        c_lines.append("")

    with open(h_path, "w", encoding="utf-8") as f:
        f.write("\n".join(h_lines))

    with open(c_path, "w", encoding="utf-8") as f:
        f.write("\n".join(c_lines))
